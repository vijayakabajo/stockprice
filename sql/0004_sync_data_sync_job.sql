BEGIN;

CREATE TABLE sync_data_sync_job (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type varchar(50) NOT NULL,
    provider varchar(50) NOT NULL,
    data_date date,
    start_time timestamptz NOT NULL,
    end_time timestamptz,
    status varchar(20) NOT NULL,
    records_processed integer DEFAULT 0 NOT NULL,
    error text
);

-- Basic indexes for filtering jobs
CREATE INDEX sync_data_sync_job_type_idx ON sync_data_sync_job (job_type);
CREATE INDEX sync_data_sync_job_status_idx ON sync_data_sync_job (status);
CREATE INDEX sync_data_sync_job_data_date_idx ON sync_data_sync_job (data_date);

COMMIT;
